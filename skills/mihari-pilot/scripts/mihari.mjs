// Pipe's RuleList has no per-rule index; array order is the evaluation order.
function loadRules(pipeRules) {
  if (pipeRules && Array.isArray(pipeRules.rules)) {
    return pipeRules.rules.map((r, i) => ({ type: r.type, payload: r.payload || '', proxy: r.proxy, index: i }));
  }
  return null;
}

// Pipe first (structured, no secret needed); mihomo controller as fallback.
// Either channel failing is reported by the caller as rules_unavailable.
async function fetchRules() {
  const pr = await api('GET', '/v1/rules', undefined, 8000);
  if (pr.ok && pr.data) {
    const rules = loadRules(pr.data);
    if (rules) return rules;
  }
  const mr = await mihomo('GET', '/rules', 6000);
  if (mr.ok && mr.json && Array.isArray(mr.json.rules)) {
    return mr.json.rules.map((r, i) => ({ type: r.type, payload: r.payload || '', proxy: r.proxy, index: typeof r.index === 'number' ? r.index : i }));
  }
  return null;
}

// First match in rule order, but remember the first rule we cannot decide
// from a bare domain (IP/process/port/geosite/ruleset). If one precedes the
// match the answer is only a hint (CONFIDENCE=approx), never a fact.
function predictRule(rules, hostName) {
  let blocker = '';
  for (const rule of rules) {
    const t = String(rule.type || '');
    const pl = String(rule.payload || '').toLowerCase();
    let match = false;
    if (t === 'Domain') match = hostName === pl;
    else if (t === 'DomainSuffix') match = hostName === pl || hostName.endsWith('.' + pl);
    else if (t === 'DomainKeyword') match = !!pl && hostName.includes(pl);
    else if (t === 'DomainRegex') { try { match = new RegExp(pl).test(hostName); } catch { match = false; } }
    else if (t === 'Match') match = true;
    else {
      if (!blocker) blocker = `${t}#${rule.index}`;
      continue;
    }
    if (match) return { rule, blocker };
  }
  return { rule: null, blocker };
}

// Evidence search, newest first: active log, then rotated .1/.2 (10 MiB x 3).
// The last line mentioning the host is not necessarily a connection line
// (providers log URLs too), so walk backwards until one parses as evidence.
function lastLogLine(hostName) {
  const files = [MIHOMO_LOG, MIHOMO_LOG + '.1', MIHOMO_LOG + '.2'];
  for (const f of files) {
    let text;
    try { text = fs.readFileSync(f, 'utf8'); } catch { continue; }
    let idx = text.lastIndexOf(hostName);
    for (let i = 0; idx >= 0 && i < 200; i++) {
      const start = text.lastIndexOf('\n', idx) + 1;
      let end = text.indexOf('\n', idx);
      if (end < 0) end = text.length;
      const line = text.slice(start, end);
      if (parseEvidence(line)) return line;
      idx = text.lastIndexOf(hostName, idx - 1);
    }
  }
  return '';
}

// mihomo writes two shapes into a JSON-wrapped log line (quotes are escaped):
//   ok   ... match <Rule>[(<payload>)] using <Group>[<Node>]
//   fail ... dial <Group> (match <Rule>[/<payload>]) <src> --> <host> error: <reason>
// The failure reason names the exit node's own server - the fastest way to
// tell "the node is dead" from "the site blocked me".
function parseEvidence(line) {
  if (!line) return '';
  const ts = (line.match(/"time":"([^"]+)"/) || [])[1] || '';
  const fail = line.match(/dial (.+?) \(match ([^)]*)\) .+? error: (.+?)\\?"/);
  if (fail) {
    const reason = fail[3].replace(/\\+$/, '').replace(/"+$/, '').replace(/\\"/g, '"');
    return `fail ${ts}  dial ${fail[1]} (match ${fail[2]}) error: ${reason}`;
  }
  // Node names may contain brackets ("[Trojan] US"); take everything up to the
  // closing bracket that ends the message, not the first one.
  const ok = line.match(/match ([A-Za-z]+)(?:\(([^)]*)\))? using (.+?)\[(.+)\](?:\\?"|$)/);
  if (ok) {
    const payload = ok[2] ? `(${ok[2]})` : '';
    return `ok ${ts}  ${ok[1]}${payload} using ${ok[3].trim()}[${ok[4]}]`;
  }
  return '';
}

