#!/usr/bin/env node
// mihari-pilot 2.0.0 - agent-facing control surface for the local mihari daemon.
// Windows-only. Node >= 18, stdlib only.
//
//   node mihari.mjs status [--probe] [--json]
//   node mihari.mjs doctor [--json]
//   node mihari.mjs trace <domain|url> [--probe] [--json]
//   node mihari.mjs env
//   node mihari.mjs on [--tun] [--probe] [--json]
//   node mihari.mjs off [--tun] [--json]
//   node mihari.mjs tui
//   node mihari.mjs nodes [group] [--probe] [--json]
//   node mihari.mjs select <group> [node] [--json]
//   node mihari.mjs subs [--json]
//   node mihari.mjs use-sub <id|name|prefix> [--json]
//   node mihari.mjs fix [domain] [--json]
//
// Exit: 0 ok | 1 ran but still offline | 2 environment problem | 3 needs the user.
//
// Output contract (stable - agents parse it, do not beautify):
//   - text mode: KEY=value status lines, then WARN=<reason> lines, then EXIT=<code>.
//   - --json mode: one JSON object INSTEAD of the text lines, WARN lines and
//     EXIT stay. `NEED_ESCALATION=1` appears only when a sandbox blocked the pipe.
//
// Two local channels, no approvals needed when the harness allows them:
//   - mihari control pipe \\.\pipe\mihari-control - HTTP/1.1, Bearer control.token.
//     Writes (sysproxy/tun/select/subscriptions/delay-test/core restart) and reads.
//   - mihomo external-controller on loopback TCP - used only for /version, /configs
//     and (as a fallback) /rules and delay probes. Needs controller-secret from
//     mihari.yaml. The mixed proxy port is a third, passive channel (TCP probe).
//
// Self-repair policy: mechanical convergence is automatic (retries, waiting for
// live state, rollback of partial switches, service/core start once). Anything
// that changes routing intent without an explicit request is not (see cmdSelect,
// cmdUseSub and cmdFix).

import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import net from 'node:net';
import http from 'node:http';
import crypto from 'node:crypto';
import { spawn, spawnSync } from 'node:child_process';

const VERSION = '2.0.0';
const PIPE_PATH = '\\\\.\\pipe\\mihari-control';
const DATA_ROOT = process.env.MIHARI_DATA || path.join(process.env.USERPROFILE || os.homedir(), '.mihari');
const SETTINGS_FILE = path.join(DATA_ROOT, 'mihari.yaml');
const TOKEN_FILE = path.join(DATA_ROOT, 'control.token');
const LOG_DIR = path.join(DATA_ROOT, 'logs');
const MIHOMO_LOG = path.join(LOG_DIR, 'mihomo.log');
const TUI_LOG = path.join(LOG_DIR, 'mihari-tui.log');
const IE_KEY = 'HKCU\\Software\\Microsoft\\Windows\\CurrentVersion\\Internet Settings';

const USAGE = 'usage: node mihari.mjs <status|doctor|trace <domain>|env|on|off|tui|nodes [group]|select <group> [node]|subs|use-sub <id|name>|fix [domain]> [--json] [--probe] [--tun]';

const warns = [];
let jsonMode = false;
let escalation = false;
let jsonPayload;
let lastLine = '';
// NEED_ESCALATION is a write-path signal: retrying a read-only command with
// wider access would buy nothing (SKILL.md says so), so only arm it for writes.
let mayEscalate = false;

const warn = (m) => warns.push(m);
const opId = () => crypto.randomBytes(16).toString('hex');
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
// In JSON mode text lines are suppressed but still remembered, so error exits
// can carry the human-readable status as `message` instead of an empty object.
const say = (...a) => {
  const text = a.map((x) => String(x)).join(' ');
  if (jsonMode) { if (text) lastLine = text; } else console.log(...a);
};

function finish(code) {
  if (jsonMode) {
    if (jsonPayload === undefined) jsonPayload = lastLine ? { message: lastLine } : {};
    // Always refresh warns: payloads are built before late warn() calls.
    jsonPayload.warns = warns.slice();
    process.stdout.write(JSON.stringify(jsonPayload) + '\n');
  }
  for (const w of warns) process.stdout.write(`WARN=${w}\n`);
  if (escalation) process.stdout.write('NEED_ESCALATION=1\n');
  process.stdout.write(`EXIT=${code}\n`);
  // Let stdout drain naturally; the watchdog only fires if a stray handle keeps us alive.
  process.exitCode = code;
  setTimeout(() => process.exit(code), 3000).unref();
}

// --json is the only flag consumed before argument splitting; everything else
// stays available to parsed.has() for per-command handling.
const args = process.argv.slice(2).filter((a) => {
  if (a === '--json') { jsonMode = true; return false; }
  return true;
});

// ------------------------------------------------------------------ settings

// Extracts three top-level scalars from mihari.yaml. A YAML parser would be
// overkill (single-file, stdlib only) and the file is generated by mihari, so
// the shape is predictable. Anything not found is reported, never silent.
function readSettings() {
  const values = {};
  const missing = [];
  let text = '';
  try {
    text = fs.readFileSync(SETTINGS_FILE, 'utf8');
  } catch {
    return { values, missing: ['<file>'], readable: false };
  }
  const get = (key) => {
    const esc = key.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const m = text.match(new RegExp(`^\\s*${esc}:\\s*"?([^"\\r\\n]*?)"?\\s*$`, 'm'));
    if (m && m[1].trim()) return m[1].trim();
    missing.push(key);
    return '';
  };
  // These are last-resort fallbacks, not defaults. Every use is reported.
  values.secret = get('controller-secret');
  values.controller = get('controller-addr') || '127.0.0.1:9090';
  values.mixed = get('mixed-addr') || '127.0.0.1:9190';
  return { values, missing, readable: true };
}

const settings = readSettings();
const yamlMixed = settings.values.mixed || '127.0.0.1:9190';
const yamlPort = yamlMixed.split(':').pop();
const controllerAddr = settings.values.controller || '127.0.0.1:9090';

// control.token is 64 lowercase hex chars + newline, written by the daemon
// (mode 0600). It is the only gate on the pipe: a wrong/absent token yields
// 401 permission_denied, which is an environment problem, not a sandbox denial.
function readToken() {
  try {
    const t = fs.readFileSync(TOKEN_FILE, 'utf8').trim();
    return t || '';
  } catch {
    return '';
  }
}

// ------------------------------------------------------------- control pipe

// One HTTP/1.1 request over the named pipe. The server mux requires
// `Host: mihari` (verified: a missing Host is a plain 400) and authenticates
// every route before routing, so even unknown paths return 401 without a token.
// `Connection: close` makes the response self-terminating - keep-alive would
// leave the socket hanging because the client cannot know the body length.
function pipeRequest(method, apiPath, body, timeoutMs) {
  return new Promise((resolve) => {
    const token = readToken();
    if (!token) return resolve({ ok: false, transport: 'no_token' });
    const payload = body === undefined ? null : JSON.stringify(body);
    let settled = false;
    const done = (v) => { if (!settled) { settled = true; resolve(v); } };
    let req;
    try {
      req = http.request({
        socketPath: PIPE_PATH,
        path: apiPath,
        method,
        headers: {
          Host: 'mihari',
          Authorization: `Bearer ${token}`,
          Connection: 'close',
          ...(payload ? { 'Content-Type': 'application/json', 'Content-Length': Buffer.byteLength(payload) } : {}),
        },
        timeout: timeoutMs || 10000,
      }, (res) => {
        const chunks = [];
        res.on('data', (c) => chunks.push(c));
        res.on('end', () => {
          const text = Buffer.concat(chunks).toString('utf8');
          const ctype = String(res.headers['content-type'] || '');
          let json = null;
          if (ctype.includes('json')) { try { json = JSON.parse(text); } catch { /* plain */ } }
          done({ ok: true, status: res.statusCode, ctype, text, json });
        });
        res.on('error', (e) => done({ ok: false, transport: e.code || 'response_error', message: e.message }));
      });
    } catch (e) {
      return done({ ok: false, transport: e.code || 'spawn_error', message: e.message });
    }
    req.on('timeout', () => {
      done({ ok: false, transport: 'timeout', message: 'request timed out' });
      req.destroy();
    });
    req.on('error', (e) => done({ ok: false, transport: e.code || 'error', message: e.message }));
    if (payload) req.write(payload);
    req.end();
  });
}

// Normalizes the three response shapes the control server can produce:
//   1. `mihari.error/v1` JSON envelopes (typed codes, used by apiErrorExit),
//   2. 401 for authentication failures,
//   3. plain-text 400/404/405 (unknown path/method/bad Host) - never JSON.
async function api(method, apiPath, body, timeoutMs) {
  const r = await pipeRequest(method, apiPath, body, timeoutMs);
  if (!r.ok) {
    return { ok: false, transport: r.transport, http: 0, code: r.transport, message: r.message || r.transport };
  }
  if (r.status === 401) {
    return { ok: false, transport: 'auth', http: 401, code: 'permission_denied', message: 'control authentication failed' };
  }
  if (r.json && r.json.error) {
    return {
      ok: false, transport: 'ok', http: r.status,
      code: r.json.error.code || 'error', message: r.json.error.message || '',
      details: r.json.error.details,
    };
  }
  if (!r.json && r.status >= 400) {
    return { ok: false, transport: 'ok', http: r.status, code: `http_${r.status}`, message: r.text.trim().slice(0, 200) };
  }
  return { ok: true, http: r.status, data: r.json, text: r.text };
}

// Transport taxonomy. Only EACCES/EPERM can mean "the sandbox blocked the
// pipe" (Windows maps named-pipe DACL denial there); ENOENT/ECONNREFUSED mean
// the daemon is not listening; no_token/auth_failed are environment problems.
function pipeState(r) {
  // transport === 'ok' means "the pipe answered"; the request itself may still
  // be a typed API error, which apiErrorExit maps by code.
  if (r.ok || r.transport === 'ok') return 'ok';
  const t = r.transport;
  if (t === 'no_token') return 'no_token';
  if (t === 'auth') return 'auth_failed';
  if (t === 'denied' || t === 'EACCES' || t === 'EPERM') return 'denied';
  if (t === 'ENOENT' || t === 'ECONNREFUSED') return 'not_found';
  if (t === 'timeout') return 'timeout';
  return 'error';
}

// Records the right WARN once and returns the state. Escalation is only armed
// for a denied pipe; retrying a sandboxed command with wider access is the one
// thing the harness can actually fix.
function notePipeProblem(r) {
  const s = pipeState(r);
  if (s === 'denied') { if (mayEscalate) escalation = true; warn('control_pipe_denied'); }
  else if (s === 'no_token') warn('control_token_missing');
  else if (s === 'auth_failed') warn('control_auth_failed');
  else if (s === 'not_found') warn('daemon_unavailable');
  else if (s === 'timeout') warn('control_timeout');
  else warn(`control_error:${r.code}`);
  return s;
}

// Typed control errors -> exit codes. 3 = the user must decide (conflicts,
// ownership, invalid state); 2 = environment (auth, args, revision); 1 = the
// write ran but the network is still down upstream. Keep this table aligned
// with SKILL.md - it is part of the published contract.
function apiErrorExit(r) {
  const s = pipeState(r);
  if (s === 'denied') { if (mayEscalate) escalation = true; warn('control_pipe_denied'); return 2; }
  if (s !== 'ok') { notePipeProblem(r); return 2; }
  switch (r.code) {
    case 'revision_conflict': warn('revision_conflict'); return 2;
    case 'system_proxy_conflict':
    case 'system_proxy_not_owned':
    case 'tun_conflict':
    case 'invalid_state': warn(r.code + (r.message ? ':' + r.message : '')); return 3;
    case 'invalid_argument': warn('invalid_argument:' + r.message); return 2;
    case 'upstream_failure':
    case 'network_failure': warn(r.code + ':' + r.message); return 1;
    case 'data_failure': warn('data_failure:' + r.message); return 1;
    default: warn(`control_error:${r.code}${r.message ? ':' + r.message : ''}`); return 2;
  }
}

// All mutations carry a 32-hex operation_id (server requires it). A revision
// conflict means someone else wrote in between (TUI, another agent): retry the
// same request once with a fresh id instead of surfacing a transient race.
async function writeOp(method, apiPath, body, timeoutMs) {
  let r = await api(method, apiPath, body, timeoutMs);
  if (!r.ok && r.code === 'revision_conflict') {
    r = await api(method, apiPath, { ...body, operation_id: opId() }, timeoutMs);
  }
  return r;
}

// ------------------------------------------------------------ mihomo channel

// Fallback read channel only. mihomo's controller does not expose mihari
// operations, so writes never go through here; it exists so status/trace still
// work when the control pipe is blocked but the controller secret is readable.
function mihomo(method, mp, timeoutMs) {
  return new Promise((resolve) => {
    const secret = settings.values.secret;
    if (!secret) return resolve({ ok: false, transport: 'no_secret' });
    const [host, port] = controllerAddr.split(':');
    let settled = false;
    const done = (v) => { if (!settled) { settled = true; resolve(v); } };
    let req;
    try {
      req = http.request({
        host, port: Number(port) || 9090, path: mp, method,
        headers: { Authorization: `Bearer ${secret}`, Connection: 'close' },
        timeout: timeoutMs || 4000,
      }, (res) => {
        const chunks = [];
        res.on('data', (c) => chunks.push(c));
        res.on('end', () => {
          const text = Buffer.concat(chunks).toString('utf8');
          let json = null;
          try { json = JSON.parse(text); } catch { /* not json */ }
          done({ ok: res.statusCode < 400, status: res.statusCode, json, text });
        });
        res.on('error', (e) => done({ ok: false, transport: e.code || 'error', message: e.message }));
      });
    } catch (e) {
      return done({ ok: false, transport: e.code || 'spawn_error', message: e.message });
    }
    req.on('timeout', () => {
      done({ ok: false, transport: 'timeout', message: 'request timed out' });
      req.destroy();
    });
    req.on('error', (e) => done({ ok: false, transport: e.code || 'error', message: e.message }));
    req.end();
  });
}

// "Is something accepting on the mixed port". A successful TCP connect is
// enough proof of life: a proxy answers even a malformed request.
function tcpUp(host, port, timeoutMs) {
  return new Promise((resolve) => {
    const sock = net.connect({ host, port: Number(port) });
    let settled = false;
    const done = (v) => { if (!settled) { settled = true; sock.destroy(); resolve(v); } };
    sock.setTimeout(timeoutMs || 1500);
    sock.once('connect', () => done(true));
    sock.once('timeout', () => done(false));
    sock.once('error', () => done(false));
  });
}

// ------------------------------------------------------------ windows probes

// mihari runs two process roles from one binary: the OS service lives in
// session 0, the TUI is an ordinary console process in the user's session.
// tasklist is used instead of PowerShell so the script stays Node-only.
function mihariProcesses() {
  const r = spawnSync('tasklist.exe', ['/FI', 'IMAGENAME eq mihari.exe', '/FO', 'CSV', '/NH'], { encoding: 'utf8', windowsHide: true });
  const rows = [];
  for (const line of String(r.stdout || '').split(/\r?\n/)) {
    const m = line.match(/^"mihari\.exe","(\d+)","([^"]*)","(\d+)"/i);
    if (m) rows.push({ pid: Number(m[1]), session: Number(m[3]) });
  }
  return { daemon: rows.filter((x) => x.session === 0), tui: rows.filter((x) => x.session !== 0) };
}

// The control API has no endpoint for service start/stop (by design: those
// need elevation), so the service state comes from sc.exe. State tokens are
// invariant English even on localized Windows.
function serviceState() {
  const r = spawnSync('sc.exe', ['query', 'mihari'], { encoding: 'utf8', windowsHide: true });
  const out = String(r.stdout || '');
  if (/RUNNING/.test(out)) return 'running';
  if (/STOPPED|STOP_PENDING/.test(out)) return 'stopped';
  if (/does not exist|1060/i.test(out) || r.status !== 0) return 'unknown';
  return 'unknown';
}

// WinINET proxy state. reg.exe keeps this PowerShell-free; missing values are
// "unreadable", not "off". mihari deliberately leaves ProxyServer behind on
// disable, so a server string while disabled is normal and must not be
// reported as a foreign proxy.
function registryProxy() {
  const read = (name) => {
    const r = spawnSync('reg.exe', ['query', IE_KEY, '/v', name], { encoding: 'utf8', windowsHide: true });
    if (r.status !== 0) return null;
    const line = String(r.stdout || '').split(/\r?\n/).find((l) => l.includes(name));
    if (!line) return null;
    const m = line.match(/REG_\w+\s+(.*)$/);
    return m ? m[1].trim() : null;
  };
  const enableRaw = read('ProxyEnable');
  const server = read('ProxyServer') || '';
  const enabled = enableRaw ? (enableRaw.toLowerCase().startsWith('0x') ? parseInt(enableRaw, 16) : parseInt(enableRaw, 10)) === 1 : false;
  return { enabled, server, readable: enableRaw !== null };
}

// MIHARI_EXE override -> PATH -> the two official install locations. Only
// needed to launch the TUI and to run `service start`; every API call is
// binary-independent.
function resolveExe() {
  if (process.env.MIHARI_EXE && fs.existsSync(process.env.MIHARI_EXE)) return process.env.MIHARI_EXE;
  const w = spawnSync('where.exe', ['mihari.exe'], { encoding: 'utf8', windowsHide: true });
  if (w.status === 0) {
    const first = String(w.stdout || '').split(/\r?\n/).find(Boolean);
    if (first) return first.trim();
  }
  const candidates = [
    path.join(process.env.LOCALAPPDATA || '', 'Programs', 'mihari', 'mihari.exe'),
    path.join(process.env.ProgramFiles || '', 'Mihari', 'mihari.exe'),
  ];
  return candidates.find((p) => p && fs.existsSync(p)) || null;
}

// The TUI opens, logs "tui started", then may fail to reach the daemon. The
// only place that is visible is its own log; check after the last start line.
function tuiLogBrokenAfterStart() {
  try {
    const size = fs.statSync(TUI_LOG).size;
    const fd = fs.openSync(TUI_LOG, 'r');
    const len = Math.min(size, 16 * 1024);
    const buf = Buffer.alloc(len);
    fs.readSync(fd, buf, 0, len, size - len);
    fs.closeSync(fd);
    const lines = buf.toString('utf8').split(/\r?\n/);
    let lastStart = -1;
    for (let i = 0; i < lines.length; i++) if (lines[i].includes('tui started')) lastStart = i;
    if (lastStart < 0) return false;
    for (let i = lastStart + 1; i < lines.length; i++) if (lines[i].includes('daemon_unavailable')) return true;
    return false;
  } catch {
    return false;
  }
}

// ------------------------------------------------------------------- groups

// Providers inject pseudo-nodes ("remaining traffic", "plan expires ...", GB
// counters) into groups. They must never be selected or auto-picked: picking
// one silently breaks every connection. Escapes keep this file pure ASCII.
const SUSPICIOUS = /\u5269\u4F59\u6D41\u91CF|\u5230\u671F|\u8FC7\u671F|\u91CD\u7F6E|\u5B98\u7F51|\u8BA2\u9605|\u6D41\u91CF|expire|traffic|\d+(\.\d+)?\s*(GB|MB|TB)/i;
// Members that are rules, not nodes. DIRECT is legitimate to *be on* but is
// never an automatic target - it means "bypass the proxy", not "a better node".
const NON_NODE = /^(REJECT|REJECT-DROP|PASS|COMPATIBLE|DIRECT)$/i;
// Codes that mean the channel itself failed (not the network target). A wrong
// token surfaces as API-level permission_denied and counts as transport too.
const TRANSPORT_CODES = new Set(['denied', 'EACCES', 'EPERM', 'ENOENT', 'ECONNREFUSED', 'no_token', 'auth', 'auth_failed', 'permission_denied', 'timeout', 'error', 'response_error', 'spawn_error']);

// /v1/proxies returns groups already ordered the way the subscription defines
// them; keep that order (panel UIs depend on it, and so does the chain walk).
function groupsFromPipe(dto) {
  return (dto && dto.groups ? dto.groups : []).map((g) => ({
    name: g.name, type: g.type || '', now: g.now || '', all: g.all || [],
  }));
}

// mihomo's /proxies is a name->proxy map without a stable order; this fallback
// only exists for when the pipe is unavailable, so order is best-effort.
function groupsFromMihomo(map) {
  const out = [];
  for (const [name, p] of Object.entries(map || {})) {
    if (Array.isArray(p.all) && p.all.length) {
      out.push({ name, type: p.type || '', now: p.now || '', all: p.all });
    }
  }
  return out;
}

function groupMap(groups) {
  return new Map(groups.map((g) => [g.name, g]));
}

// Walks `now` from a group (or node) to the terminal node. A group name that
// is also a member means nesting; the loop guard and depth cap make a
// misconfigured provider harmless instead of an infinite call.
function resolveChain(groups, start) {
  const byName = groupMap(groups);
  const chain = [];
  let cur = start;
  for (let i = 0; i < 6 && cur; i++) {
    chain.push(cur);
    const g = byName.get(cur);
    if (!g) break;
    const nxt = g.now;
    if (!nxt || chain.includes(nxt)) break;
    cur = nxt;
  }
  return chain;
}

// Preferred primary selector names are matched via the escaped list below,
// then any selector, then anything - so a renamed group never leaves status
// without a chain.
function primaryGroup(groups) {
  const byName = groupMap(groups);
  const names = ['\u8282\u70B9\u9009\u62E9', '\u9009\u62E9\u8282\u70B9', 'Proxy', 'PROXY'];
  // Names are often decorated ("🔰 节点选择"), so match by suffix too.
  for (const n of names) {
    const exact = byName.get(n);
    if (exact) return exact;
    const suffixed = groups.find((g) => g.name.endsWith(n));
    if (suffixed) return suffixed;
  }
  const selectors = groups.filter((g) => g.type === 'Selector' && g.name !== 'GLOBAL');
  if (selectors.length) return selectors[0];
  return groups.find((g) => g.type === 'Selector') || groups[0] || null;
}

function primaryChain(groups) {
  const g = primaryGroup(groups);
  if (!g) return [];
  return resolveChain(groups, g.name);
}

function suspiciousName(name) {
  return SUSPICIOUS.test(name || '');
}

// A "real node" is a proxy node, not a rule, not a nested group, and not a
// provider pseudo-node. This is the single gate used by select/fix auto-picks.
function isRealNodeMember(groups, name) {
  if (!name || NON_NODE.test(name) || suspiciousName(name)) return false;
  if (groupMap(groups).has(name)) return false;
  return true;
}

// Resolution order: exact -> case-insensitive exact -> unique substring.
// Ambiguity is never guessed: callers turn the candidate list into EXIT=3.
function resolveGroup(groups, needle) {
  const exact = groups.find((g) => g.name === needle);
  if (exact) return { group: exact };
  const lower = needle.toLowerCase();
  const ci = groups.filter((g) => g.name.toLowerCase() === lower);
  if (ci.length === 1) return { group: ci[0] };
  const partial = groups.filter((g) => g.name.toLowerCase().includes(lower));
  if (partial.length === 1) return { group: partial[0] };
  if (partial.length > 1) return { candidates: partial.map((g) => g.name) };
  return { candidates: [] };
}

// Same resolution rules as resolveGroup, applied to node names inside a group.
function resolveNodeName(names, needle) {
  const exact = names.find((n) => n === needle);
  if (exact) return { name: exact };
  const lower = needle.toLowerCase();
  const ci = names.filter((n) => n.toLowerCase() === lower);
  if (ci.length === 1) return { name: ci[0] };
  const partial = names.filter((n) => n.toLowerCase().includes(lower));
  if (partial.length === 1) return { name: partial[0] };
  if (partial.length > 1) return { candidates: partial };
  return { candidates: [] };
}

// ---------------------------------------------------------------- probes

// Delays map member -> milliseconds; 0/missing means the test failed. The API
// reports failures as an error envelope for single proxies, so only positive
// numbers count as healthy here.
function parseDelay(r, key) {
  if (!r.ok) return { ok: false, code: r.code || r.transport };
  const delays = r.data && r.data.delays ? r.data.delays : {};
  const ms = delays[key];
  if (typeof ms === 'number' && ms > 0) return { ok: true, ms };
  return { ok: false, code: 'delay_failed' };
}

// The delay test runs INSIDE the daemon/mihomo, not in this process: a
// restricted sandbox denies Windows Schannel credentials, so any local TLS
// request would report a false "network down". An empty url makes the daemon
// use the core-configured test URL instead of a hardcoded one. The mihomo
// fallback is plain-HTTP-first because https-only targets have measured false
// failures on otherwise healthy nodes.
async function probeNode(node, testURL) {
  if (!node || node === 'unknown') return { ok: false, code: 'no_node' };
  const r = await api('POST', `/v1/proxies/${encodeURIComponent(node)}/delay-test`, { url: testURL || '', timeout_ms: 6000 }, 20000);
  const viaPipe = parseDelay(r, node);
  if (r.ok || pipeState(r) === 'ok') return viaPipe;
  // Pipe unavailable: fall back to mihomo's own delay test (plain HTTP first: an
  // https-only target has measured false failures on some nodes).
  const targets = testURL ? [testURL] : ['http://www.gstatic.com/generate_204', 'https://www.cloudflare.com/cdn-cgi/trace'];
  let last = 'delay_failed';
  for (const u of targets) {
    const mp = `/proxies/${encodeURIComponent(node)}/delay?timeout=6000&url=${encodeURIComponent(u)}`;
    const mr = await mihomo('GET', mp, 12000);
    if (!mr.ok) { last = 'controller_unreachable'; break; }
    if (mr.json && typeof mr.json.delay === 'number' && mr.json.delay > 0) return { ok: true, ms: mr.json.delay };
    if (mr.json && mr.json.message) last = String(mr.json.message);
  }
  return { ok: false, code: last };
}

// One daemon-side test for every member of a group. Used for auto-pick and for
// fix's candidate search; a 30s client timeout covers ~100 members.
async function groupDelay(group, testURL) {
  const r = await api('POST', `/v1/proxy-groups/${encodeURIComponent(group)}/delay-test`, { url: testURL || '', timeout_ms: 6000 }, 30000);
  if (!r.ok) return { ok: false, code: r.code || r.transport, delays: {} };
  return { ok: true, delays: (r.data && r.data.delays) || {} };
}

