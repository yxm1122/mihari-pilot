// One snapshot used by every read-only command. Precedence rules:
//   - live core values win over mihari.yaml (a port change may be unapplied);
//   - sysproxy ownership comes from the daemon; a foreign proxy is reported,
//     never clobbered;
//   - when the pipe is up, /v1/core and /v1/routing still answer without a
//     controller secret, so status degrades instead of going blind;
//   - mihomo /rules is NOT fetched here (trace asks only when needed).
async function collectState() {
  const st = {
    pipe: 'ok', daemonVersion: '', health: '', protocol: '', caps: [],
    sys: { enabled: false, server: '', owned: false, foreign: false, unknown: false },
    tun: { live: false, unknown: false },
    groups: [], chain: [], mode: 'unknown',
    mixed: { host: yamlMixed.split(':')[0], livePort: yamlPort, up: false },
    core: { up: false, version: '' },
    reg: { enabled: false, server: '', readable: false },
    tui: [], daemonProc: false,
  };
  st.reg = registryProxy();
  const [statusR, sysR, tunR, groupsR] = await Promise.all([
    api('GET', '/v1/status', undefined, 5000),
    api('GET', '/v1/system-proxy', undefined, 5000),
    api('GET', '/v1/tun', undefined, 5000),
    api('GET', '/v1/proxies', undefined, 8000),
  ]);
  if (statusR.ok && statusR.data) {
    st.daemonVersion = statusR.data.daemon_version || '';
    st.health = statusR.data.health || '';
    st.protocol = statusR.data.protocol_version || '';
    st.caps = statusR.data.capabilities || [];
  } else {
    st.pipe = notePipeProblem(statusR);
  }
  if (sysR.ok && sysR.data) {
    const o = sysR.data.observed || {};
    st.sys = {
      enabled: !!o.enabled, server: o.server || '', owned: !!o.owned,
      foreign: !!o.foreign || (!!o.enabled && !o.owned), unknown: false,
    };
  } else if (st.reg.readable) {
    // Pipe unavailable: WinINET still answers "is anything set". Ownership is
    // unknowable, so any server other than ours is treated as foreign.
    const expected = `${st.mixed.host}:${st.mixed.livePort}`;
    st.sys = {
      enabled: st.reg.enabled, server: st.reg.server, owned: false,
      foreign: st.reg.enabled && !!st.reg.server && st.reg.server !== expected, unknown: false,
    };
  } else {
    st.sys.unknown = true;
  }
  let tunKnown = false;
  if (tunR.ok && tunR.data) {
    st.tun = { live: tunR.data.live_enable === true, unknown: false };
    tunKnown = true;
  }
  if (groupsR.ok && groupsR.data) st.groups = groupsFromPipe(groupsR.data);

  const [verR, cfgR, coreR, routingR] = await Promise.all([
    mihomo('GET', '/version'), mihomo('GET', '/configs'),
    api('GET', '/v1/core', undefined, 5000), api('GET', '/v1/routing', undefined, 5000),
  ]);
  if (verR.ok && verR.json) { st.core.up = true; st.core.version = String(verR.json.version || ''); }
  if (coreR.ok && coreR.data) {
    if (String(coreR.data.status || '').toLowerCase() === 'running') st.core.up = true;
    if (coreR.data.version) st.core.version = String(coreR.data.version);
  }
  if (cfgR.ok && cfgR.json) {
    if (cfgR.json.mode) st.mode = String(cfgR.json.mode);
    if (cfgR.json['mixed-port']) st.mixed.livePort = String(cfgR.json['mixed-port']);
    if (typeof cfgR.json.tun?.enable === 'boolean' && tunR.ok === false) {
      st.tun.live = cfgR.json.tun.enable;
      tunKnown = true;
    }
  }
  if (!tunKnown) st.tun.unknown = true;
  // Registry-derived sysproxy: recompute "foreign" with the live port.
  if (!sysR.ok && st.reg.readable) {
    const expected = `${st.mixed.host}:${st.mixed.livePort}`;
    st.sys.foreign = st.reg.enabled && !!st.reg.server && st.reg.server !== expected;
  }
  if (st.mode === 'unknown' && routingR.ok && routingR.data && routingR.data.mode) st.mode = String(routingR.data.mode);
  if (!st.groups.length) {
    // Pipe blocked (sandbox) or core down: mihomo can still answer /proxies.
    const px = await mihomo('GET', '/proxies', 8000);
    if (px.ok && px.json && px.json.proxies) st.groups = groupsFromMihomo(px.json.proxies);
  }
  st.chain = primaryChain(st.groups);
  const procs = mihariProcesses();
  st.tui = procs.tui;
  st.daemonProc = procs.daemon.length > 0;
  // The pipe reports ownership authoritatively; the registry alone cannot
  // distinguish mihari's proxy from another tool's. Only trust pipe ownership
  // when /v1/system-proxy actually answered (not a registry fallback).
  if (st.pipe === 'ok' && sysR.ok && st.sys.enabled) {
    st.sys.foreign = !st.sys.owned;
  }
  st.mixed.up = await tcpUp(st.mixed.host, st.mixed.livePort);
  return st;
}

// WARN taxonomy for status/on/off. Each line names one explainable condition;
// callers print them after the state line so the first line stays stable.
function stateWarnings(st) {
  if (settings.missing.length) warn('settings_missing_from_config:' + settings.missing.join(','));
  if (!resolveExe()) warn('mihari_not_found');
  if (st.sys.unknown) warn('sysproxy_state_unknown');
  if (st.tun.unknown) warn('tun_state_unknown');
  if (!st.daemonProc && st.pipe !== 'ok' && serviceState() !== 'running') warn('daemon_stopped');
  if (st.pipe === 'ok') {
    if (!st.core.up) warn('core_down');
  } else if (!st.core.up) {
    warn(settings.values.secret ? 'core_down' : 'mihari_config_unreadable');
  }
  if (st.core.up && st.mixed.livePort !== yamlPort) warn(`mixed_port_drift:yaml=${yamlPort},live=${st.mixed.livePort}`);
  if (st.sys.enabled && st.tun.live) warn('sysproxy_and_tun_both_on');
  if (st.sys.foreign && st.sys.server) warn('foreign_sysproxy:' + st.sys.server);
  const tail = st.chain.length ? st.chain[st.chain.length - 1] : '';
  if (tail && suspiciousName(tail)) warn('suspicious_node:' + tail);
}

// The published one-line status format. Do not reorder fields: agents and the
// SKILL.md contract parse them positionally by key.
function stateLine(st, probeText) {
  const sys = st.sys.unknown ? 'unknown'
    : (st.sys.enabled ? (st.sys.foreign ? `on(foreign:${st.sys.server})` : 'on') : 'off');
  const tunText = st.tun.unknown ? 'unknown' : (st.tun.live ? 'on' : 'off');
  let state = 'off';
  if (st.sys.unknown || st.tun.unknown) state = 'unknown';
  else if (st.sys.enabled && st.tun.live) state = 'conflict';
  else if (st.tun.live) state = 'tun';
  else if (st.sys.enabled) state = 'sysproxy';
  let core = 'unknown';
  if (st.core.up) core = st.core.version ? `running/${st.core.version}` : 'running';
  else if (st.pipe === 'ok' || settings.values.secret) core = 'down';
  let daemon = 'stopped';
  if (st.daemonProc || st.pipe === 'ok') daemon = 'running';
  const tui = st.tui.length ? `present:${st.tui[0].pid}` : 'absent';
  const envSet = process.env.HTTP_PROXY || process.env.HTTPS_PROXY || process.env.ALL_PROXY ? 'set' : 'unset';
  const chain = st.chain.length ? st.chain.join('>') : 'unknown';
  return `STATE=${state} SYS=${sys} TUN=${tunText} CORE=${core} DAEMON=${daemon} `
    + `NODE=${chain} MODE=${st.mode} MIXED=${st.mixed.livePort}:${st.mixed.up ? 'up' : 'down'} TUI=${tui} ENV=${envSet} PROBE=${probeText}`;
}

