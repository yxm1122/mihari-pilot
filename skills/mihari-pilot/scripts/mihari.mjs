// Prediction vs observation. The prediction walks the rule table and current
// selections; the observation is the last real connection for this host. When
// they disagree the group re-selected in between, so EVIDENCE wins. A bare IP
// cannot be decided by domain rules, so only EVIDENCE is meaningful there.
async function cmdTrace() {
  const target = rest[0];
  if (!target) { say('ERROR=trace_needs_a_domain'); say('USAGE=trace <domain|url> [--probe]'); finish(2); return; }
  let hostName = target.toLowerCase().replace(/^[a-z][a-z0-9+.-]*:\/\//, '');
  hostName = hostName.split('/')[0].split(':')[0].replace(/\.+$/, '');
  const st = await collectState();
  const rules = await fetchRules();
  if (!rules) {
    warn('rules_unavailable');
    say(`TRACE=${hostName} RULE=unknown CHAIN=unknown NODE=unknown CONFIDENCE=none`);
    finish(2);
    return;
  }
  const { rule, blocker } = predictRule(rules, hostName);
  let ruleText = 'none_matched';
  let chain = [];
  if (rule) {
    ruleText = rule.payload ? `${rule.type}(${rule.payload})->${rule.proxy}` : `${rule.type}->${rule.proxy}`;
    chain = resolveChain(st.groups, rule.proxy);
    if (!chain.length) chain = [rule.proxy];
  }
  const node = chain.length ? chain[chain.length - 1] : 'unknown';
  let confidence = blocker ? 'approx' : 'exact';
  if (blocker) warn(`rule_order_preceded_by_undecidable:${blocker}`);
  if (/^[0-9]{1,3}(\.[0-9]{1,3}){3}$/.test(hostName)) {
    confidence = 'none';
    warn('trace_target_is_ip_ip_rules_not_evaluated');
  }
  if (suspiciousName(node)) warn('suspicious_node:' + node);
  say(`TRACE=${hostName} RULE=${ruleText} CHAIN=${chain.length ? chain.join('>') : 'unknown'} NODE=${node} CONFIDENCE=${confidence}`);
  let probeText;
  if (parsed.has('--probe')) {
    const p = await probeNode(node);
    probeText = p.ok ? `ok(${p.ms}ms)` : `fail(${p.code})`;
    say(`PROBE=${probeText}`);
  }
  const evidence = parseEvidence(lastLogLine(hostName));
  say('EVIDENCE=' + (evidence || 'none_no_recent_connection_in_log'));
  if (!evidence) warn('evidence_none:host_unseen_log_level_rotated_or_never_forwarded');
  jsonPayload = { trace: { target: hostName, rule: ruleText, chain: chain.join('>') || 'unknown', node, confidence }, probe: probeText || null, evidence: evidence || null, warns: warns.slice() };
  finish(0);
}

// The system proxy only covers WinINET apps. These variables are for the
